#!/usr/bin/env node
/**
 * Generates the frontend's typed ABIs and address book.
 *
 *   npm run gen:abis                          forge build, then read contracts/out
 *   npm run gen:abis -- --no-build            reuse an existing contracts/out
 *   npm run gen:abis -- --from-json <file>    split a combined file:
 *                                             { chainId, addresses: { Name: "0x..." }, abis: { Name: [...] } }
 *                                             (a flat { Name: [...] } ABI map also works)
 *
 * Writes:
 *   src/abis/<Name>.ts     one typed ABI per contract (`as const`), plus src/abis/index.ts
 *   src/config/deployment.json   addresses only: { chainId, external, contracts }
 *
 * Addresses come from, in order: --from-json `addresses`, then contracts/deployments/current.json
 * (`.contracts` and `.startBlock`, written by the forge deploy scripts). With neither, the existing
 * deployment.json is kept.
 *
 * The generated files are committed so the Vercel build does not need Foundry.
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const frontendDir = path.resolve(import.meta.dirname, "..");
const contractsDir = path.resolve(frontendDir, "..", "contracts");
const abisDir = path.join(frontendDir, "src", "abis");
const configPath = path.join(frontendDir, "src", "config", "deployment.json");

/** ABIs the frontend uses. Contract name -> forge artifact file. */
const CONTRACTS = [
  "QuantumRound",
  "WaveV4ProposalMarket",
  "WavefundVault",
  "ProposerRegistry",
  "ProposalTokens",
  "ProposalToken",
  "MockPriceOracle",
  "Resolver",
  "TestAsset",
  "WaveHook",
  "WavefundPoolHelper",
];

/** Contracts we do not deploy. Their addresses live under `external`. */
const EXTERNAL = new Set(["USDC", "PoolManager", "Multicall3", "Permit2"]);

const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const option = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};

const lowerFirst = (s) => s.charAt(0).toLowerCase() + s.slice(1);
const readJson = (file) => JSON.parse(fs.readFileSync(file, "utf8"));

// ---------------------------------------------------------------- ABIs

let abiMap = {};
let addressBook = null;
let chainId = null;
let deployBlock = null;

const fromJson = option("--from-json");
if (fromJson) {
  const combined = readJson(path.resolve(process.cwd(), fromJson));
  abiMap = combined.abis ?? combined;
  addressBook = combined.addresses ?? null;
  chainId = combined.chainId ?? null;
} else {
  if (!flag("--no-build")) {
    console.log("forge build (tests and scripts skipped)...");
    const res = spawnSync("forge", ["build", "--skip", "test", "--skip", "script"], {
      cwd: contractsDir,
      stdio: "inherit",
    });
    if (res.status !== 0) {
      console.error("forge build failed. Fix the build, or run with --no-build to reuse contracts/out.");
      process.exit(res.status ?? 1);
    }
  }
  for (const name of CONTRACTS) {
    const artifact = path.join(contractsDir, "out", `${name}.sol`, `${name}.json`);
    if (!fs.existsSync(artifact)) {
      console.error(`Missing artifact for ${name}: ${artifact}`);
      process.exit(1);
    }
    abiMap[name] = readJson(artifact).abi;
  }
}

fs.rmSync(abisDir, { recursive: true, force: true });
fs.mkdirSync(abisDir, { recursive: true });

const exports = [];
for (const name of CONTRACTS) {
  const abi = abiMap[name];
  if (!abi) {
    console.error(`No ABI for ${name} in the input.`);
    process.exit(1);
  }
  const constName = `${lowerFirst(name)}Abi`;
  fs.writeFileSync(
    path.join(abisDir, `${name}.ts`),
    `// Generated by scripts/gen-abis.mjs. Do not edit by hand.\n\nexport const ${constName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  exports.push(`export { ${constName} } from "./${name}";`);
  console.log(`  ${name}: ${abi.length} ABI entries`);
}
fs.writeFileSync(
  path.join(abisDir, "index.ts"),
  `// Generated by scripts/gen-abis.mjs. Do not edit by hand.\n\n${exports.join("\n")}\n`,
);

// ---------------------------------------------------------------- addresses

if (!addressBook) {
  const book = path.join(contractsDir, "deployments", "current.json");
  if (fs.existsSync(book)) {
    const current = readJson(book);
    addressBook = current.contracts ?? null;
    chainId = chainId ?? current.chainId ?? null;
    deployBlock = current.startBlock ?? current.deployBlock ?? null;
  }
}

if (addressBook) {
  const previous = fs.existsSync(configPath) ? readJson(configPath) : {};
  const contracts = {};
  const external = { ...(previous.external ?? {}) };
  for (const [name, address] of Object.entries(addressBook)) {
    if (!/^0x[0-9a-fA-F]{40}$/.test(address)) continue;
    if (EXTERNAL.has(name)) external[name] = address;
    else contracts[name] = address;
  }
  fs.mkdirSync(path.dirname(configPath), { recursive: true });
  fs.writeFileSync(
    configPath,
    JSON.stringify(
      {
        network: "arc-testnet",
        chainId: chainId ?? previous.chainId ?? 5042002,
        external,
        contracts,
        ...((deployBlock ?? previous.deployBlock) ? { deployBlock: deployBlock ?? previous.deployBlock } : {}),
      },
      null,
      2,
    ) + "\n",
  );
  console.log(`Wrote src/config/deployment.json (${Object.keys(contracts).length} contracts)`);
} else {
  console.log("No addresses in the input: kept the existing src/config/deployment.json");
}

// ---------------------------------------------------------------- agents

// agents/agents.json holds public data only (address, name, type, description). Copied so the
// Vercel build, which only sees frontend/, has it.
const agentsSource = path.resolve(frontendDir, "..", "agents", "agents.json");
if (fs.existsSync(agentsSource)) {
  const agents = readJson(agentsSource);
  fs.writeFileSync(path.join(frontendDir, "src", "config", "agents.json"), `${JSON.stringify(agents, null, 2)}\n`);
  console.log(`Wrote src/config/agents.json (${agents.agents?.length ?? 0} agents)`);
}
