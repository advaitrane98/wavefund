// npm run write:sources   Merges transactions and verification links into current.json and writes SOURCES.md.
import fs from 'node:fs';
import path from 'node:path';
import { BOOK_FILE, DEPLOYMENTS_DIR, EXPLORER, addressUrl, loadBook, txUrl } from './demo-round-common.mjs';
import { allBroadcasts } from './lib/broadcast.mjs';
import { verificationStatus } from './verify-contracts.mjs';

const book = loadBook();
const txs = allBroadcasts();
const created = Object.fromEntries(txs.filter((t) => t.contractName && t.contractAddress).map((t) => [t.contractName, t]));
// WaveHook is created through the CREATE2 factory, so its deployment is the DeployWaveHook transaction that is not setWaveHook.
const hookTx = txs.find((t) => t.script === 'DeployWaveHook' && !/setWaveHook/.test(t.function ?? ''));
if (hookTx) created.WaveHook = hookTx;
const local = /127\.0\.0\.1|localhost/.test(process.env.ARC_TESTNET_RPC ?? '');

const transactions = {};
const verification = {};
const rows = [];
for (const [name, address] of Object.entries(book.c)) {
  const t = created[name];
  if (t) transactions[name] = { hash: t.hash, block: t.block, gasUsed: t.gasUsed };
  const external = name === 'USDC' || name === 'PoolManager';
  const status = external || local ? { verified: false } : await verificationStatus(address);
  verification[name] = external ? 'external' : status.verified ? `${addressUrl(address)}?tab=contract` : 'not verified';
  rows.push(`| ${name} | [\`${address}\`](${addressUrl(address)}) | ${t ? `[\`${t.hash.slice(0, 10)}...\`](${txUrl(t.hash)})` : external ? 'pre-existing' : '-'} | ${t?.block ?? '-'} | ${external ? 'n/a' : status.verified ? `[verified](${addressUrl(address)}?tab=contract)` : 'not verified'} |`);
}
const wiring = txs.filter((t) => t.script === 'Wire' || /setWaveHook/.test(t.function ?? ''));
fs.writeFileSync(BOOK_FILE, JSON.stringify({ ...book, transactions, verification, updatedAt: new Date().toISOString() }, null, 2));

const md = `# Wavefund deployment sources (Arc Testnet)

Chain ID ${book.chainId}. Explorer: ${EXPLORER}. Deployer: \`${book.deployer}\`. Keeper: \`${book.keeper}\`.
Generated by \`npm run write:sources\`. Machine-readable copy: \`contracts/deployments/current.json\`.

| Contract | Address | Deployment tx | Block | Source |
|---|---|---|---|---|
${rows.join('\n')}

## Wiring transactions

${wiring.length ? wiring.map((t) => `- ${t.function ?? 'call'}: [\`${t.hash}\`](${txUrl(t.hash)}) (block ${t.block ?? '?'}, gas ${t.gasUsed ?? '?'})`).join('\n') : '- none recorded'}

## Notes

- The hook is deployed through the standard CREATE2 factory with a mined salt (flags 2752): \`${book.hookSalt ?? 'n/a'}\`.
- Ownership of the market moves to QuantumRound automatically once both setters are called.
- Verified with \`forge verify-contract --verifier blockscout\`.
`;
const dest = process.env.SOURCES_FILE || path.join(DEPLOYMENTS_DIR, 'SOURCES.md');
fs.writeFileSync(dest, md);
console.log(`wrote ${dest} and updated ${BOOK_FILE}`);
